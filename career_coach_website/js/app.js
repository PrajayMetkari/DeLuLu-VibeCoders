document.addEventListener("DOMContentLoaded", () => {
  const menu = document.getElementById("menuToggle");
  const sidebar = document.getElementById("sidebar");
  if (menu && sidebar) menu.addEventListener("click", () => sidebar.classList.toggle("open"));

  // Local-only interactive prototype helpers (not AI-backed unless an API is connected).
  document.querySelectorAll("[data-demo-form]").forEach(form => {
    form.addEventListener("submit", event => {
      event.preventDefault();
      const input = form.querySelector("input, textarea");
      const output = form.querySelector("[data-demo-output]");
      if (!input || !output || !input.value.trim()) return;
      const userText = input.value.trim();
      const response = form.dataset.reply || "Thanks for sharing that. Use the Portfolio Analysis module to compare your project evidence with a target role. This prototype response is not generated by an AI model.";
      const userNode = document.createElement("div");
      userNode.className = "chat-message user";
      userNode.textContent = userText;
      const assistantNode = document.createElement("div");
      assistantNode.className = "chat-message";
      const label = document.createElement("span");
      label.className = "chat-label";
      label.textContent = "CAREERPILOT GUIDE · DEMO";
      const body = document.createElement("div");
      body.textContent = response;
      assistantNode.append(label, body);
      output.classList.remove("hidden");
      output.append(userNode, assistantNode);
      input.value = "";
      output.scrollTop = output.scrollHeight;
    });
  });

  const tasks = [...document.querySelectorAll("[data-progress-task]")];
  const fill = document.querySelector("[data-progress-fill]");
  const label = document.querySelector("[data-progress-label]");
  const count = document.querySelector("[data-progress-count]");
  const currentPage = window.location.pathname;
  const storageKey = currentPage.includes("training.html")
    ? "careerpilot-training-tasks-v1"
    : "careerpilot-weekly-mastery-tasks-v1";
  if (tasks.length) {
    try {
      const saved = JSON.parse(localStorage.getItem(storageKey) || "[]");
      tasks.forEach((task, i) => task.checked = Boolean(saved[i]));
    } catch (_) {}
    const update = () => {
      const done = tasks.filter(task => task.checked).length;
      const pct = Math.round(done / tasks.length * 100);
      if (fill) fill.style.width = pct + "%";
      if (label) label.textContent = pct + "% complete";
      if (count) count.textContent = `${done} of ${tasks.length} tasks complete`;
      try { localStorage.setItem(storageKey, JSON.stringify(tasks.map(task => task.checked))); } catch (_) {}
    };
    tasks.forEach(task => task.addEventListener("change", update));
    update();
  }
});

document.addEventListener('DOMContentLoaded', () => {
    const submitBtn = document.getElementById('submitBtn');
    if (submitBtn) {
        submitBtn.addEventListener('click', async () => {
            const githubUrl = document.getElementById('githubUrl').value;
            const jobDescription = document.getElementById('jobDesc').value;

            if (!githubUrl || !jobDescription) {
                alert('Please fill in both fields!');
                return;
            }

            const report = await evaluateRepository(githubUrl, jobDescription);

            if (report) {
                console.log("AI Report Received:", report);
                alert("Success! Match Score: " + report.candidate_match_score + "%");
            }
        });
    }
});